/** Keywords found in the name/first sentence count three times: "a commercial law firm advising on property" is law, not property. */
export function pickRecipe(primary: string, secondary = ""): Recipe {
  const a = primary.toLowerCase();
  const b = secondary.toLowerCase();
  let best: Recipe | undefined;
  let bestScore = 0;
  for (const r of RECIPES) {
    let score = 0;
    for (const k of r.keywords) {
      const w = k.length >= 6 ? 2 : 1;
      if (a.includes(k)) score += 3 * w;
      else if (b.includes(k)) score += w;
    }
    if (score > bestScore) {
      best = r;
      bestScore = score;
    }
  }
  return best ?? RECIPES[RECIPES.length - 1]!;
}
