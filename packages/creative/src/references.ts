/**
 * Reference Atlas: design MEMORY, not a template inventory. Each entry records a transferable principle, where it
 * works and where it fails, and which first-party grammar it informed. Nothing here is copied: no layouts, copy,
 * imagery, logos or motion are reproduced, and entries are never shown to customers as "templates".
 *
 * Evidence is stated, not implied, and only the first kind counts as "studied":
 *  - DIRECT_SITE_REVIEW  the live site was retrieved and its fonts, colours, radii and structure were read from the
 *                        fetch (2026-11-02), not from memory. A larger, RENDERED study of 182 sites (computed styles at
 *                        desktop and phone width) is recorded separately in docs/research/data and
 *                        docs/research/SITE-OBSERVATIONS-2026.md; that corpus, not this list, is what the research
 *                        count rests on.
 *  - SEARCH_LEAD         the site was named by a search result (usually a vendor or agency roundup); it was not opened.
 *                        Kept as a lead for future study. NOT counted as studied.
 *  - ANALYST_MEMORY      Kora's design analysis from general knowledge of the brand; NOT re-verified live. A principle
 *                        worth keeping, but NOT counted as studied.
 * Counts are asserted in tests so the documentation cannot drift into claiming more than was done.
 */
export type Evidence = "DIRECT_SITE_REVIEW" | "SEARCH_LEAD" | "ANALYST_MEMORY";
export interface Reference {
  id: string;
  name: string;
  category: string;
  evidence: Evidence;
  /** The transferable design principle (what to learn). */
  principle: string;
  /** The one recognisable thing the work does. */
  signature: string;
  whyItWorks: string;
  whenItFails: string;
  smallBusinessApplicability: string;
  /** Grammar ids this reference informed. */
  informs: string[];
  observed?: {
    type?: string;
    colour?: string;
    shape?: string;
    structure?: string;
  };
  doNotCopy: string;
}
