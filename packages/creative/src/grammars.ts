/**
 * Design grammars: the first-party design languages Kora composes with. Each is a small coherent set of decisions
 * (a genome, colourways, a signature device, anti-patterns), not a template. Content, page architecture and copy are
 * produced elsewhere; a grammar only says how a business should feel and be set.
 *
 * Grammars were derived from principles in docs/research/AGENCY-CREATIVE-SYSTEM-2026.md. None names or imitates a
 * third-party brand; names below are Kora's own.
 */
import {
  DesignGenomeSchema,
  type DesignGenome,
  type HeroLayout,
} from "./genome.js";
import { luminance } from "./color.js";

export interface Colorway {
  id: string;
  label: string;
  bg: string;
  fg: string;
  primary: string;
  secondary: string;
  accent: string;
  mode: "light" | "dark";
}
const cw = (
  id: string,
  label: string,
  bg: string,
  fg: string,
  primary: string,
  secondary: string,
  accent: string,
): Colorway => ({
  id,
  label,
  bg,
  fg,
  primary,
  secondary,
  accent,
  mode: luminance(bg) < 0.25 ? "dark" : "light",
});

export interface Grammar {
  id: string;
  name: string;
  /** One line: what a stranger should feel. */
  concept: string;
  /** "{thing}" is replaced by what the business actually offers, in the owner's words. */
  essence: string;
  personality: string[];
  tags: string[];
  emotionalGoal: string;
  visualTension: string;
  voice: string;
  tone: string;
  conversionMood: string;
  signature: { name: string; description: string };
  antiPatterns: string[];
  campaignBehaviour: string;
  motionNote: string;
  /** Words in the owner's "feel" that pull a business toward this grammar. */
  feel: string;
  colorways: Colorway[];
  genome: DesignGenome;
  /** Controlled variation so two businesses sharing a grammar still differ. */
  alternates: {
    hero: HeroLayout[];
    service: DesignGenome["servicePresentation"][];
    motif: DesignGenome["signatureMotif"][];
    headline: DesignGenome["headlineBehavior"][];
    radius: DesignGenome["radiusStyle"][];
    header: DesignGenome["headerStyle"][];
  };
}

