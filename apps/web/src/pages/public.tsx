function AuthForm({ mode }: { mode: "login" | "signup" }) {
  const nav = useNavigate();
  const loc = useLocation();
  const { refresh } = useAuth();
  const [err, setErr] = useState<string | null>(null);
  const [busy, setBusy] = useState(false);
  const submit = async (e: FormEvent<HTMLFormElement>) => {
    e.preventDefault();
    const f = new FormData(e.currentTarget);
    setBusy(true);
    setErr(null);
    try {
      await api(
        "POST",
        `/api/auth/${mode}`,
        mode === "login"
          ? { email: f.get("email"), password: f.get("password") }
          : {
              email: f.get("email"),
              password: f.get("password"),
              displayName: f.get("displayName"),
              orgName: f.get("orgName"),
            },
      );
      await refresh();
      nav(
        mode === "signup"
          ? "/app/sites/new"
          : ((loc.state as { from?: string } | null)?.from ?? "/app"),
      );
    } catch (x) {
      setErr(errText(x));
    } finally {
      setBusy(false);
    }
  };
  return (
    <div className="wrap narrow" style={{ padding: "48px 20px" }}>
      <form className="card stack" onSubmit={submit}>
        <h1 style={{ fontSize: "2rem" }}>
          {mode === "login" ? "Welcome back" : "Create your account"}
        </h1>
        {mode === "signup" && (
          <>
            <label>
              Your name
              <input
                name="displayName"
                required
                maxLength={80}
                autoComplete="name"
              />
            </label>
            <label>
              Business name
              <input
                name="orgName"
                required
                maxLength={120}
                autoComplete="organization"
              />
            </label>
          </>
        )}
        <label>
          Email
          <input name="email" type="email" required autoComplete="email" />
        </label>
        <label>
          Password
          <input
            name="password"
            type="password"
            required
            minLength={mode === "signup" ? 10 : 1}
            autoComplete={
              mode === "signup" ? "new-password" : "current-password"
            }
          />
          {mode === "signup" && (
            <span className="field-hint">At least 10 characters.</span>
          )}
        </label>
        {err && <Notice kind="bad">{err}</Notice>}
        <button className="btn" disabled={busy}>
          {busy
            ? "Please wait…"
            : mode === "login"
              ? "Sign in"
              : "Create account"}
        </button>
        <p className="small muted">
          {mode === "login" ? (
            <>
              New here? <Link to="/signup">Create an account</Link>
            </>
          ) : (
            <>
              Already have an account? <Link to="/login">Sign in</Link>
            </>
          )}
        </p>
      </form>
    </div>
  );
}
export const Login = () => <AuthForm mode="login" />;
export const Signup = () => <AuthForm mode="signup" />;

